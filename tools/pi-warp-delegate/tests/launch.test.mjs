function inPty(command, args, f, env) {
  const argv = process.platform === 'darwin'
    ? ['-q', '/dev/null', command, ...args]
    : ['-q', '-e', '-c', shellCommand([command, ...args]), '/dev/null'];
  return spawnSync('/usr/bin/script', argv, {
    cwd: f.workspace, env, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 15_000,
  });
}
const hasPty = existsSync('/usr/bin/script') && ['darwin', 'linux'].includes(process.platform);

test('TOML serialization round-trips quotes, controls, Unicode, backslashes and shell metacharacters', () => {
  for (const value of ['空格 中文', "'single' \"double\"", '\n\r\t\b\f\x00\x1f\x7f\x85', '\\x $() `id`', 'emoji 🐈']) {
    assert.equal(TOML.parse(`value = ${tomlString(value)}\n`).value, value);
  }
  assert.throws(() => shellQuote('bad\0value'), { exitCode: 2 });
});

test('launch copies input, binds an independent session, emits only terminal-pane configs and passes no credentials', async (t) => {
  const f = fixture(t);
  f.env.OPENAI_API_KEY = 'DO_NOT_COPY_THIS_SECRET';
  f.env.PI_SESSION_FILE = '/do/not/copy/parent.jsonl';
  const original = readFileSync(f.promptFile);
  const result = await launch(f.options, f.runtime);
  assert.equal(result.action, 'launch_requested');
  assert.notEqual(result.sessionId, f.env.PI_SESSION_ID);
  assert.match(result.sessionId, /^[a-f0-9-]{36}$/);
  const ctx = await parentContext(f.runtime, {});
  const directory = join(ctx.directory, result.sessionId);
  assert.deepEqual(readFileSync(join(directory, 'prompt.md')), original);
  assert.deepEqual(readFileSync(f.promptFile), original);
  assert.deepEqual(readdirSync(directory).sort(), ['launch.sh', 'prompt.md', 'protocol.md', 'state.json']);
  const configFile = join(f.home, '.warp', 'tab_configs', readdirSync(join(f.home, '.warp', 'tab_configs'))[0]);
  const config = TOML.parse(readFileSync(configFile, 'utf8'));
  assert.equal(config.panes[0].type, 'terminal');
  assert.equal(config.panes[0].shell, 'zsh');
  assert.equal(config.panes[0].directory, f.cwd);
  assert.equal(config.title, f.options.name);
  assert.equal(config.panes[0].commands.length, 1);
  const script = readFileSync(join(directory, 'launch.sh'), 'utf8');
  assert.match(script, /--session-id/);
  assert.match(script, /--append-system-prompt/);
  assert.doesNotMatch(script, /'--(?:extension|print|mode|continue|no-session|approve)'/);
  assert.match(script, /unset PI_SESSION_ID PI_SESSION_FILE PI_PROVIDER PI_MODEL PI_REASONING_LEVEL/);
  for (const path of [...readdirSync(directory).map((name) => join(directory, name)), configFile]) {
    assert.equal(statSync(path).mode & 0o777, 0o600);
    assert.doesNotMatch(readFileSync(path, 'utf8'), /DO_NOT_COPY_THIS_SECRET|\/do\/not\/copy\/parent/);
  }
  const protocol = readFileSync(join(directory, 'protocol.md'), 'utf8');
  assert.match(protocol, /不接收结果/);
  assert.match(protocol, /TERMINAL_STATE/);
  assert.match(protocol, /report.*--state in_progress/);
  assert.match(protocol, /结案后用户继续聊天/);
  assert.equal(f.opens.length, 1);
  assert.equal(existsSync(f.env.TEST_PI_RECORD), false);
});

test('literal Warp templates never enter interpolated TOML fields', async (t) => {
  const f = fixture(t, ' {{autogenerated_branch_name}}');
  const plan = await prepareLaunch({ ...f.options, name: 'title {{branch}}\nnext' }, f.runtime);
  assert.doesNotMatch(plan.tabConfig, /\{\{/);
  const config = TOML.parse(plan.tabConfig);
  assert.equal(config.panes[0].directory, '/');
  assert.equal(config.title, 'title ｛｛branch}} next');
  assert.ok(plan.script.includes(shellQuote(f.cwd)), 'the real project directory is still used inside the script');
  assert.ok(plan.script.includes(shellQuote('title {{branch}}\nnext')), 'Pi receives the original explicit name');
  assert.deepEqual(readdirSync(f.home), []);
});

test('non-TTY execution cannot silently turn the delegated Pi into print mode', async (t) => {
  const f = fixture(t);
  const result = await launch(f.options, f.runtime);
  const ctx = await parentContext(f.runtime, {});
  const directory = join(ctx.directory, result.sessionId);
  const attempt = spawnSync('/bin/sh', [join(directory, 'launch.sh')], { env: f.env, encoding: 'utf8', timeout: 5_000 });
  assert.equal(attempt.status, 1);
  assert.match(attempt.stderr, /Refusing non-TTY/);
  assert.equal(existsSync(join(directory, '.launch-claimed')), false);
  assert.equal(existsSync(f.env.TEST_PI_RECORD), false);
  assert.equal((await new Store().status(ctx, result.sessionId)).state, 'launching');
});

test('generated Warp command safely reaches an interactive fake Pi with exact argv, cwd and binding', { skip: !hasPty }, async (t) => {
  const f = fixture(t, " ' \" \\ $(touch PWNED) `touch PWNED2`\n{{literal}} 中文");
  // Also exercise an installed CLI path containing shell syntax and Warp templates.
  const copiedCli = join(f.root, "tool ' $(touch PWNED3) {{tool}}");
  mkdirSync(copiedCli);
  cpSync(dirname(cliPath), copiedCli, { recursive: true });
  writeFileSync(join(copiedCli, 'package.json'), '{"type":"module"}');
  f.runtime.cliPath = join(copiedCli, 'cli.js');
  f.options.name = "task ' \" \\ $(touch PWNED4) `touch PWNED5`\n{{title}} 中文";
  writeFileSync(f.promptFile, "$(touch PWNED6)\n`touch PWNED7`\n'; exit 9; #\n--print\n");
  const result = await launch(f.options, f.runtime);
  const ctx = await parentContext(f.runtime, {});
  const directory = join(ctx.directory, result.sessionId);
  const configFile = join(f.home, '.warp', 'tab_configs', readdirSync(join(f.home, '.warp', 'tab_configs'))[0]);
  const config = TOML.parse(readFileSync(configFile, 'utf8'));
  const env = { ...f.env, TEST_REPORT_ON_START: 'completed', TEST_CLI: f.runtime.cliPath };
  const executed = inPty('/bin/sh', ['-c', config.panes[0].commands[0]], f, env);
  assert.equal(executed.status, 0, `${executed.error ?? ''}\n${executed.stdout}\n${executed.stderr}`);
  const record = JSON.parse(readFileSync(f.env.TEST_PI_RECORD, 'utf8'));
  assert.equal(record.inputTTY, true);
  assert.equal(record.outputTTY, true);
  assert.equal(record.cwd, f.cwd);
  assert.equal(record.parent, ctx.directory);
  assert.equal(record.child, result.sessionId);
  assert.equal(record.inheritedPiSessionId, null);
  assert.equal(record.inheritedProvider, null);
  assert.deepEqual(record.argv, [
    '--session-id', result.sessionId, '--name', f.options.name,
    '--model', f.options.model, '--thinking', f.options.thinking,
    '--append-system-prompt', join(directory, 'protocol.md'), '--', `@${join(directory, 'prompt.md')}`,
    '请执行随附任务文档中的委派任务，并按委派任务状态协议主动上报状态。',
  ]);
  assert.deepEqual(record.report, { sessionId: result.sessionId, state: 'completed' });
  assert.equal((await new Store().status(ctx, result.sessionId)).state, 'completed');
  assert.deepEqual(readFileSync(join(directory, 'prompt.md')), readFileSync(f.promptFile));
  for (const marker of ['PWNED', 'PWNED2', 'PWNED3', 'PWNED4', 'PWNED5', 'PWNED6', 'PWNED7']) {
    for (const root of [f.workspace, f.cwd, f.root, f.home]) assert.equal(existsSync(join(root, marker)), false, marker);
  }
  const previous = readFileSync(f.env.TEST_PI_RECORD, 'utf8');
  const repeated = inPty('/bin/sh', [join(directory, 'launch.sh')], f, env);
  assert.match(repeated.stdout + repeated.stderr, /one-time launch/);
  assert.equal(readFileSync(f.env.TEST_PI_RECORD, 'utf8'), previous, 'saved Tab Config cannot run the same task twice');
  assert.equal((await new Store().status(ctx, result.sessionId)).state, 'completed');
});

test('even a real process exit of the fake Pi cannot infer or change task state', { skip: !hasPty }, async (t) => {
  const f = fixture(t);
  const result = await launch(f.options, f.runtime);
  const ctx = await parentContext(f.runtime, {});
  const executed = inPty('/bin/sh', [join(ctx.directory, result.sessionId, 'launch.sh')], f, f.env);
  assert.equal(executed.status, 0, executed.stdout + executed.stderr);
  assert.equal(existsSync(f.env.TEST_PI_RECORD), true);
  assert.equal((await new Store().status(ctx, result.sessionId)).state, 'launching');
});

test('shell shims and unsupported platforms fail preflight without invoking them', async (t) => {
  const f = fixture(t);
  writeFileSync(f.piPath, '#!/bin/sh\ntouch PWNED\n');
  await assert.rejects(() => resolvePi(f.runtime), { code: 'UNSUPPORTED_PI_ENTRY' });
  await assert.rejects(() => prepareLaunch(f.options, { ...f.runtime, platform: 'linux' }), { code: 'UNSUPPORTED_PLATFORM' });
  assert.equal(existsSync(join(f.workspace, 'PWNED')), false);
  assert.deepEqual(readdirSync(f.home), []);
});
